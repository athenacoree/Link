let IDIOMA_ACTUAL = localStorage.getItem('enlace_idioma') || 'es';

function t(clave) {
  const dict = DICCIONARIO_I18N[IDIOMA_ACTUAL] || DICCIONARIO_I18N.es;
  return dict[clave] || DICCIONARIO_I18N.es[clave] || clave;
}

function aplicarTraduccionesDOM() {
  document.querySelectorAll('[data-i18n]').forEach((elem) => {
    const key = elem.getAttribute('data-i18n');
    if (key) {
      elem.textContent = t(key);
    }
  });

  document.querySelectorAll('[data-i18n-ph]').forEach((elem) => {
    const key = elem.getAttribute('data-i18n-ph');
    if (key) {
      elem.placeholder = t(key);
    }
  });

  // Actualizar selects de idioma si existen
  document.querySelectorAll('.select-idioma-app').forEach((sel) => {
    sel.value = IDIOMA_ACTUAL;
  });

  // Repoblar selects de países y estados según el idioma actual
  if (typeof window.poblarSelectPaises === 'function') {
    const regPaisSelect = document.getElementById('regPais');
    if (regPaisSelect) {
      const valPais = regPaisSelect.value || 'CU';
      window.poblarSelectPaises(regPaisSelect, IDIOMA_ACTUAL, valPais);
      const regEstadoSelect = document.getElementById('regEstado');
      if (regEstadoSelect) {
        const valEst = regEstadoSelect.value;
        window.poblarSelectEstados(regEstadoSelect, regPaisSelect.value, IDIOMA_ACTUAL, valEst);
      }
    }

    const edPaisSelect = document.getElementById('edPais');
    if (edPaisSelect) {
      const valPaisEd = edPaisSelect.value || 'CU';
      window.poblarSelectPaises(edPaisSelect, IDIOMA_ACTUAL, valPaisEd);
      const edEstadoSelect = document.getElementById('edEstadoSelect');
      if (edEstadoSelect) {
        const valEstEd = edEstadoSelect.value;
        window.poblarSelectEstados(edEstadoSelect, edPaisSelect.value, IDIOMA_ACTUAL, valEstEd);
      }
    }
  }
}

function cambiarIdioma(nuevoIdioma) {
  if (nuevoIdioma !== 'es' && nuevoIdioma !== 'en') return;
  IDIOMA_ACTUAL = nuevoIdioma;
  localStorage.setItem('enlace_idioma', nuevoIdioma);
  aplicarTraduccionesDOM();

  // Si el usuario tiene sesión activa, actualizar en backend
  if (window.Sesion && window.Sesion.activa && window.Sesion.activa()) {
    const u = window.Sesion.usuario();
    if (u) {
      const settings = u.settings || {};
      settings.language = nuevoIdioma;
      if (typeof window.api === 'function') {
        window.api('/usuarios/me/configuraciones', { method: 'PUT', body: settings }).catch(() => {});
      }
    }
  }

  if (typeof window.mostrarToast === 'function') {
    window.mostrarToast(nuevoIdioma === 'en' ? 'Language changed to English' : 'Idioma cambiado a Español');
  }
}

document.addEventListener('DOMContentLoaded', () => {
  aplicarTraduccionesDOM();
});

window.DICCIONARIO_I18N = DICCIONARIO_I18N;
window.IDIOMA_ACTUAL = IDIOMA_ACTUAL;
window.t = t;
window.aplicarTraduccionesDOM = aplicarTraduccionesDOM;
window.cambiarIdioma = cambiarIdioma;
